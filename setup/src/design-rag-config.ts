import { execa } from 'execa';
import chalk from 'chalk';
import inquirer from 'inquirer';
import fs from 'fs-extra';
import path from 'path';

interface DesignRagConfig {
  knowbUrl: string;
  ssoHost: string;
}

export class DesignRagConfigSetup {
  private config: DesignRagConfig = {
    knowbUrl: 'https://knowb.api.int.test-godaddy.com',
    ssoHost: 'sso.test-godaddy.com'
  };

  async checkSsoJwtBinary(): Promise<boolean> {
    try {
      await execa('ssojwt', ['--version']);
      return true;
    } catch {
      return false;
    }
  }

  async generateSsoJwtToken(): Promise<string | null> {
    console.log(chalk.blue('🔄 Generating SSO JWT token for test environment...'));

    try {
      const { stdout: token } = await execa('ssojwt', ['-e', 'test']);
      const trimmedToken = token.trim();

      if (trimmedToken) {
        console.log(chalk.green('✅ SSO JWT token generated successfully'));
        console.log(chalk.gray(`   Token: ${trimmedToken.substring(0, 20)}...`));
        return trimmedToken;
      }

      throw new Error('Empty token received');
    } catch (error: any) {
      console.log(chalk.red('❌ Failed to generate SSO JWT token'));
      console.log(chalk.gray(`   Error: ${error.message}`));
      return null;
    }
  }

  async generateDesignRagEnvContent(token: string): Promise<string> {
    return `# Design RAG Configuration
# Generated by setup utility
# For KnowB knowledge base integration

# SSO JWT token for authentication (test environment)
SSO_JWT=${token}

# KnowB API URL (test environment)
KNOWB_URL=${this.config.knowbUrl}

# SSO Host for S2S authentication (if needed)
# SSO_HOST=${this.config.ssoHost}
# GOCODE_USE_S2S_AUTH=false
`;
  }

  async setup(yesToAll: boolean = false): Promise<{ success: boolean; envPath?: string; token?: string }> {
    console.log(chalk.cyan.bold('🎨 Design RAG Environment Setup'));
    console.log(chalk.gray('================================'));
    console.log('');

    console.log('Design RAG is used for experimental RAG data processing pipelines.');
    console.log(`KnowB API URL: ${this.config.knowbUrl}`);
    console.log('Authentication: SSO JWT token (test environment)');
    console.log('');
    console.log(chalk.gray('CLI tools available after setup:'));
    console.log(chalk.gray('  pnpm --filter @airo/design-rag upload <file>'));
    console.log(chalk.gray('  pnpm --filter @airo/design-rag search <query>'));
    console.log(chalk.gray('  pnpm --filter @airo/design-rag process <file>'));
    console.log('');

    if (yesToAll) {
      console.log(chalk.gray('Automated mode: attempting Design RAG configuration...'));
    }

    if (!yesToAll) {
      const { proceed } = await inquirer.prompt([
        {
          type: 'confirm',
          name: 'proceed',
          message: 'Continue with Design RAG configuration?',
          default: true
        }
      ]);

      if (!proceed) {
        console.log(chalk.yellow('Design RAG configuration cancelled.'));
        return { success: false };
      }
    }

    // Check if ssojwt binary is available
    const hasSsoJwtBinary = await this.checkSsoJwtBinary();

    let token: string | null = null;

    if (hasSsoJwtBinary) {
      console.log(chalk.green('✅ ssojwt binary found'));
      console.log('');

      if (yesToAll) {
        token = await this.generateSsoJwtToken();
      } else {
        const { method } = await inquirer.prompt([
          {
            type: 'list',
            name: 'method',
            message: 'How would you like to configure authentication?',
            choices: [
              { name: 'Generate SSO JWT token automatically (recommended)', value: 'generate' },
              { name: 'Enter SSO JWT token manually', value: 'manual' }
            ],
            default: 'generate'
          }
        ]);

        if (method === 'generate') {
          token = await this.generateSsoJwtToken();
        } else {
          const { manualToken } = await inquirer.prompt([
            {
              type: 'password',
              name: 'manualToken',
              message: 'Enter your SSO JWT token:',
              validate: (input) => input.length > 0 || 'SSO JWT Token is required'
            }
          ]);
          token = manualToken;
          console.log(chalk.green('✅ SSO JWT token configured'));
        }
      }
    } else {
      console.log(chalk.yellow('⚠️  ssojwt binary not found'));
      console.log(chalk.blue('📦 Install from: https://github.com/gdcorp-engineering/ssojwt'));
      console.log('');

      if (yesToAll) {
        console.log(chalk.yellow('Automated mode: skipping Design RAG configuration (ssojwt not available)'));
        return { success: false };
      }

      const { hasToken } = await inquirer.prompt([
        {
          type: 'confirm',
          name: 'hasToken',
          message: 'Do you have an SSO JWT token to enter manually?',
          default: false
        }
      ]);

      if (hasToken) {
        const { manualToken } = await inquirer.prompt([
          {
            type: 'password',
            name: 'manualToken',
            message: 'Enter your SSO JWT token:',
            validate: (input) => input.length > 0 || 'SSO JWT Token is required'
          }
        ]);
        token = manualToken;
        console.log(chalk.green('✅ SSO JWT token configured'));
      } else {
        console.log(chalk.yellow('Design RAG configuration skipped - no token available.'));
        console.log('');
        console.log(chalk.yellow('Manual setup instructions:'));
        console.log('1. Install ssojwt from https://github.com/gdcorp-engineering/ssojwt');
        console.log('2. Run: ssojwt -e test');
        console.log('3. Create design-rag/.env with:');
        console.log(chalk.gray(`   SSO_JWT=<your-token>`));
        console.log(chalk.gray(`   KNOWB_URL=${this.config.knowbUrl}`));
        return { success: false };
      }
    }

    if (!token) {
      console.log(chalk.red('❌ Could not obtain SSO JWT token'));
      return { success: false };
    }

    console.log('');
    console.log(chalk.green.bold('🎉 Design RAG configuration ready!'));
    console.log('');

    return { success: true, token };
  }

  async writeEnvFile(projectRoot: string, token: string, yesToAll: boolean = false): Promise<boolean> {
    // Resolve and validate paths to prevent path traversal
    const resolvedRoot = path.resolve(projectRoot);
    const designRagDir = path.resolve(resolvedRoot, 'design-rag');
    const designRagEnvPath = path.resolve(designRagDir, '.env');

    // Ensure paths are within project root
    if (!designRagDir.startsWith(resolvedRoot) || !designRagEnvPath.startsWith(designRagDir)) {
      console.log(chalk.red('❌ Invalid path detected'));
      return false;
    }

    // Check if design-rag directory exists
    if (!await fs.pathExists(designRagDir)) {
      console.log(chalk.red('❌ design-rag directory not found'));
      console.log(chalk.yellow('Make sure the design-rag package is installed'));
      return false;
    }

    const envContent = await this.generateDesignRagEnvContent(token);

    // Check if .env already exists
    if (await fs.pathExists(designRagEnvPath)) {
      if (!yesToAll) {
        const { overwrite } = await inquirer.prompt([
          {
            type: 'confirm',
            name: 'overwrite',
            message: 'design-rag/.env already exists. Overwrite it?',
            default: false
          }
        ]);

        if (!overwrite) {
          console.log(chalk.yellow('⏭  Keeping existing design-rag/.env'));
          return true;
        }
      } else {
        console.log(chalk.gray('Automated mode: overwriting existing design-rag/.env'));
      }
    }

    try {
      await fs.writeFile(designRagEnvPath, envContent);
      console.log(chalk.green(`✅ Generated design-rag/.env file`));
      return true;
    } catch (error: any) {
      console.log(chalk.red('❌ Failed to write design-rag/.env'));
      console.log(chalk.gray(`   Error: ${error.message}`));
      return false;
    }
  }

  async quickCheck(): Promise<boolean> {
    console.log(chalk.blue('🔍 Quick Design RAG configuration check...'));

    // Check if ssojwt binary is available
    const hasSsoJwtBinary = await this.checkSsoJwtBinary();

    if (!hasSsoJwtBinary) {
      console.log(chalk.yellow('⚠️  ssojwt binary not installed'));
      console.log(chalk.gray('   Install from: https://github.com/gdcorp-engineering/ssojwt'));
      return false;
    }

    // Try to generate a token to verify it works
    try {
      const { stdout: token } = await execa('ssojwt', ['-e', 'test']);
      if (token && token.trim()) {
        console.log(chalk.green('✅ Design RAG authentication is available (ssojwt works)'));
        return true;
      }
    } catch {
      console.log(chalk.yellow('⚠️  ssojwt failed to generate token'));
      return false;
    }

    return false;
  }
}
