import { posix } from 'node:path';

import { translateDockerPath } from '../../utils/path-helper.js';

/**
 * The two legal pages the compliance-docs skill owns. When the skill is
 * available these may only be written through the validated compliance route
 * (which handles any credit charge and patches annotated spans) — never via the
 * generic file-write APIs or the agent text-editor tool. See GAI-1614.
 *
 * Lives in the skill's own directory (not shared tooling) per the skill
 * self-containment rule — see agents/src/skills/README.md.
 */
const COMPLIANCE_MANAGED_RELATIVE_PATHS = ['src/pages/privacy.tsx', 'src/pages/terms.tsx'] as const;

/** Steering error shown when a direct write to a compliance-managed page is blocked. */
export const COMPLIANCE_MANAGED_WRITE_ERROR =
  'This page is managed by the compliance tool. Use compliance-docs__generate_privacy_policy or ' +
  'compliance-docs__generate_terms_of_use to create or regenerate it — do not edit this file directly. Do not retry.';

/**
 * Exact-match the two compliance-owned pages. Normalizes docker (`/app/…`),
 * leading-slash, `./`, and `..` segments to a workspace-relative posix path, then
 * compares. Pure comparison — the path is NEVER used for file I/O — so it
 * deliberately avoids `path.resolve` on the input (no path-traversal sink).
 * Exact match only — other `src/pages/*` files stay freely editable.
 */
export function isComplianceManagedPath(filePath: string): boolean {
  const normalized: string = posix.normalize(translateDockerPath(filePath)).replace(/^\/+/, '');
  return (COMPLIANCE_MANAGED_RELATIVE_PATHS as readonly string[]).includes(normalized);
}
