/**
 * Integration tests for the auto-conform path of contentRulesPostEditHandler.
 *
 * These run against REAL temp app dirs with a real `vite.config.ts` +
 * `src/pages/index.tsx`. The handler reads/writes customer files through an
 * injected `WorkspaceFiles` (TempWorkspaceFiles, rooted at the same temp
 * appPath), while the real content-scaffold machinery writes content files via
 * `node:fs` to that same tree — the only way to prove the snapshot/validate/
 * rollback boundary restores files byte-for-byte across both mechanisms.
 */

import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { CreateForWorkspace } from '../../workspace/client.js';
import type {
  PostEditCommand,
  PostEditContext,
} from '../../tools/ai-lib-tools/post-edit-handlers.js';
import { createContentRulesPostEditHandler } from '../content-rules-post-edit-handler.js';
import { tempWorkspaceFactory } from './temp-workspace-files.js';

const ADVISORY_MARKER: string = 'content-rules-lint found';
const CONFORMED_MARKER: string = 'Conformed to the content layer';

const VITE_CONFIG: string = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
});
`;

// One clean extractable array (testimonials) + one that declines (features holds
// a non-literal \`icon\` identifier value), mirroring the proven fixture.
const PAGE: string = `import { Zap } from 'lucide-react';

const testimonials = [
  { quote: "great", name: "Jordan", tag: "owner" },
  { quote: "love it", name: "Priya", tag: "fan" },
];

const features = [
  { icon: Zap, title: "A", desc: "d" },
];

export default function HomePage() {
  return (
    <div className={features[0] ? '' : ''}>
      {features.map((f) => <h3 key={f.title}>{f.title}</h3>)}
      {testimonials.map((t) => <p key={t.name}>{t.quote}</p>)}
    </div>
  );
}
`;

let dir: string | undefined;

interface AppLayout {
  appPath: string;
  pageRel: string;
  pageFull: string;
  factory: CreateForWorkspace;
}

function setupApp(
  pageRel: string,
  pageSource: string,
  withExistingContent: boolean = false,
): AppLayout {
  const created: string = mkdtempSync(join(tmpdir(), 'auto-conform-'));
  mkdirSync(join(created, 'src', 'pages'), { recursive: true });
  writeFileSync(join(created, 'vite.config.ts'), VITE_CONFIG);
  const pageFull: string = join(created, pageRel);
  mkdirSync(join(created, pageRel, '..'), { recursive: true });
  writeFileSync(pageFull, pageSource);

  if (withExistingContent) {
    // A prior `home` content root (the binding the conform scaffolds into) whose
    // testimonials items carry ids, plus a POSITIONAL lock in .user-edits.json
    // (`home.testimonials[0].quote`). The real `mode:'merge'` scaffold rekeys
    // that positional `[0]` → `[@id]` and REWRITES .user-edits.json — so the
    // rollback test genuinely proves the lock file is restored to its original
    // positional bytes, not merely left untouched.
    mkdirSync(join(created, 'src', 'content', 'pages'), { recursive: true });
    writeFileSync(
      join(created, 'src', 'content', 'pages', 'home.json'),
      JSON.stringify(
        {
          testimonials: [
            { id: 'seed-1', quote: 'great', name: 'Jordan', tag: 'owner' },
            { id: 'seed-2', quote: 'love it', name: 'Priya', tag: 'fan' },
          ],
        },
        null,
        2,
      ) + '\n',
    );
    writeFileSync(
      join(created, 'src', 'content', 'schemas.ts'),
      `import { z } from 'zod';\n\nexport const schemas = {\n  home: z.object({ testimonials: z.array(z.object({ "id": z.string(), quote: z.string(), name: z.string(), tag: z.string() })) }),\n};\n\nexport type Schemas = typeof schemas;\n`,
    );
    writeFileSync(
      join(created, 'src', 'content', 'virtual-content.d.ts'),
      `// AUTO-GENERATED by content_scaffold — do not edit.\ndeclare module 'virtual:content' {\n  export const home: { testimonials: Array<{ "id": string; quote: string; name: string; tag: string }> };\n}\n`,
    );
    // Correct lock-file shape is { "lockedKeys": [...] } (see content-user-edits.ts).
    writeFileSync(
      join(created, 'src', 'content', '.user-edits.json'),
      JSON.stringify({ lockedKeys: ['home.testimonials[0].quote'] }, null, 2) + '\n',
    );
  }

  return { appPath: created, pageRel, pageFull, factory: tempWorkspaceFactory(created) };
}

function makeContext(layout: AppLayout, command: PostEditCommand): PostEditContext {
  return {
    fullPath: layout.pageFull,
    filePath: layout.pageRel,
    appPath: layout.appPath,
    appId: 'app-auto-conform',
    command,
  };
}

function runHandler(layout: AppLayout, command: PostEditCommand, result: string): Promise<string> {
  const handler = createContentRulesPostEditHandler({ workspaceFactory: layout.factory });
  return handler.run(makeContext(layout, command), result);
}

beforeEach(() => {
  dir = undefined;
});
afterEach(() => {
  if (dir) rmSync(dir, { recursive: true, force: true });
  vi.restoreAllMocks();
});

describe('contentRulesPostEditHandler — auto-conform (happy path, fresh app)', () => {
  it('moves a clean array into the content layer, registers the vite plugin, rewrites the page, and replaces the advisory with a conformed note', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;

    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    const homeJsonPath: string = join(dir, 'src/content/pages/home.json');
    expect(existsSync(homeJsonPath)).toBe(true);

    // round-trip fidelity: items minus the minted id deep-equal the source data
    const json: Record<string, unknown> = JSON.parse(readFileSync(homeJsonPath, 'utf8'));
    const testimonials: Array<Record<string, unknown>> = json.testimonials as Array<
      Record<string, unknown>
    >;
    const stripIds: Array<Record<string, unknown>> = testimonials.map((item) => {
      const { id: _id, ...rest } = item;
      return rest;
    });
    expect(stripIds).toEqual([
      { quote: 'great', name: 'Jordan', tag: 'owner' },
      { quote: 'love it', name: 'Priya', tag: 'fan' },
    ]);

    const vite: string = readFileSync(join(dir, 'vite.config.ts'), 'utf8');
    expect(vite).toMatch(/contentPlugin/);

    const page: string = readFileSync(layout.pageFull, 'utf8');
    expect(page).toMatch(/import \{ home \} from 'virtual:content'/);
    expect(page).toMatch(/home\.testimonials\.map\(/);
    expect(page).not.toMatch(/const testimonials =/);

    expect(result).toContain('File created successfully.');
    expect(result).toContain(CONFORMED_MARKER);
    expect(result).toContain('testimonials');
    expect(result).toContain('home.testimonials');
    expect(result).not.toContain(ADVISORY_MARKER);
  });

  it('removes a rogue src/content/index.ts barrel during conform', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;
    mkdirSync(join(dir, 'src', 'content'), { recursive: true });
    writeFileSync(join(dir, 'src', 'content', 'index.ts'), `export * from './pages/home.json';\n`);

    await runHandler(layout, 'create', 'File created successfully.');

    expect(existsSync(join(dir, 'src', 'content', 'index.ts'))).toBe(false);
  });
});

describe('contentRulesPostEditHandler — auto-conform (gates)', () => {
  it('command gate: str_replace does not conform (file unchanged)', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;

    await runHandler(layout, 'str_replace', 'ok');

    expect(existsSync(join(dir, 'src/content'))).toBe(false);
    expect(readFileSync(layout.pageFull, 'utf8')).toBe(PAGE);
  });

  it('command gate: insert does not conform (file unchanged)', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;

    await runHandler(layout, 'insert', 'ok');

    expect(existsSync(join(dir, 'src/content'))).toBe(false);
    expect(readFileSync(layout.pageFull, 'utf8')).toBe(PAGE);
  });

  it('path gate: a src/components/*.tsx create does not conform', async () => {
    const layout: AppLayout = setupApp('src/components/Widget.tsx', PAGE);
    dir = layout.appPath;

    await runHandler(layout, 'create', 'ok');

    expect(existsSync(join(dir, 'src/content'))).toBe(false);
    expect(readFileSync(layout.pageFull, 'utf8')).toBe(PAGE);
  });

  it('nothing extractable: a page with only declinable arrays does not conform and keeps the advisory unchanged', async () => {
    const ONLY_DECLINABLE: string = `import { Zap } from 'lucide-react';

const features = [
  { icon: Zap, title: "A", desc: "d" },
];

export default function HomePage() {
  return <div>{features.map((f) => <h3 key={f.title}>{f.title}</h3>)}</div>;
}
`;
    const layout: AppLayout = setupApp('src/pages/index.tsx', ONLY_DECLINABLE);
    dir = layout.appPath;

    const before: string = readFileSync(layout.pageFull, 'utf8');
    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    expect(existsSync(join(dir, 'src/content'))).toBe(false);
    expect(readFileSync(layout.pageFull, 'utf8')).toBe(before);
    expect(result).not.toContain(CONFORMED_MARKER);
  });
});

describe('contentRulesPostEditHandler — auto-conform (rollback on validation failure)', () => {
  it('restores every touched file byte-identical when validation fails — fresh app', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;
    const pageBefore: string = readFileSync(layout.pageFull, 'utf8');
    const viteBefore: string = readFileSync(join(dir, 'vite.config.ts'), 'utf8');

    // Sabotage the round-trip check: stub scaffoldContent so the written JSON
    // does NOT match the extracted data, forcing the deep-equal validation to fail.
    const scaffold = await import('../../tools/content-scaffold.js');
    vi.spyOn(scaffold, 'scaffoldContent').mockImplementation(async (contentDir: string) => {
      const { promises: fsp } = await import('node:fs');
      await fsp.mkdir(join(contentDir, 'pages'), { recursive: true });
      await fsp.writeFile(
        join(contentDir, 'pages', 'home.json'),
        JSON.stringify({ testimonials: [{ id: 'x', quote: 'WRONG' }] }, null, 2) + '\n',
      );
      await fsp.writeFile(
        join(contentDir, 'schemas.ts'),
        `import { z } from 'zod';\nexport const schemas = { home: z.object({}) };\nexport type Schemas = typeof schemas;\n`,
      );
      return {
        ok: true as const,
        file: join(contentDir, 'pages', 'home.json'),
        relFile: 'src/content/pages/home.json',
        importLine: "import { home } from 'virtual:content';",
        schemasCreated: true,
        key: 'home',
      };
    });

    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    expect(readFileSync(layout.pageFull, 'utf8')).toBe(pageBefore);
    expect(readFileSync(join(dir, 'vite.config.ts'), 'utf8')).toBe(viteBefore);
    expect(existsSync(join(dir, 'src/content/pages/home.json'))).toBe(false);
    expect(existsSync(join(dir, 'src/content/schemas.ts'))).toBe(false);
    expect(existsSync(join(dir, 'src/content/virtual-content.d.ts'))).toBe(false);
    expect(result).not.toContain(CONFORMED_MARKER);
  });

  it('clean merge onto EXISTING locked content SUCCEEDS (no false round-trip rollback)', async () => {
    // Regression for the merge-mode round-trip bug: scaffold(merge) preserves
    // user-locked on-disk values over the freshly-inlined data, so a strict
    // round-trip on a PRE-EXISTING array would false-fail and silently decline.
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE, /* withExistingContent */ true);
    dir = layout.appPath;

    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    // It must conform, not roll back to advisory.
    expect(result).toContain(CONFORMED_MARKER);
    expect(readFileSync(layout.pageFull, 'utf8')).toContain('home.testimonials.map');
    const home: { testimonials: { id: string; quote: string }[] } = JSON.parse(
      readFileSync(join(dir, 'src/content/pages/home.json'), 'utf8'),
    );
    expect(Array.isArray(home.testimonials)).toBe(true);
  });

  it('vite.config missing AFTER scaffold (fresh app) → rolls back scaffold’s node:fs writes via the Workspace API', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;
    const pageBefore: string = readFileSync(layout.pageFull, 'utf8');
    // Force the post-scaffold vite-registration step to fail → rollback.
    rmSync(join(dir, 'vite.config.ts'));

    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    // scaffold wrote src/content/* via node:fs; rollback must remove them through
    // the Workspace API (the cross-mechanism invariant).
    expect(existsSync(join(dir, 'src/content/pages/home.json'))).toBe(false);
    expect(existsSync(join(dir, 'src/content/schemas.ts'))).toBe(false);
    expect(existsSync(join(dir, 'src/content/virtual-content.d.ts'))).toBe(false);
    expect(readFileSync(layout.pageFull, 'utf8')).toBe(pageBefore);
    expect(result).not.toContain(CONFORMED_MARKER);
  });

  it('vite.config missing AFTER scaffold (existing app) → restores content + .user-edits.json byte-identical', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE, /* withExistingContent */ true);
    dir = layout.appPath;
    const userEditsPath: string = join(dir, 'src/content/.user-edits.json');
    const snap: Record<string, string> = {
      page: readFileSync(layout.pageFull, 'utf8'),
      homeJson: readFileSync(join(dir, 'src/content/pages/home.json'), 'utf8'),
      schemas: readFileSync(join(dir, 'src/content/schemas.ts'), 'utf8'),
      dts: readFileSync(join(dir, 'src/content/virtual-content.d.ts'), 'utf8'),
      userEdits: readFileSync(userEditsPath, 'utf8'),
    };
    expect(snap.userEdits).toContain('home.testimonials[0].quote'); // positional lock
    rmSync(join(dir, 'vite.config.ts')); // force post-scaffold rollback

    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    // Real scaffold ran (rekeying .user-edits.json), then rollback restored every
    // touched file — including the lock file — byte-identical.
    expect(readFileSync(join(dir, 'src/content/pages/home.json'), 'utf8')).toBe(snap.homeJson);
    expect(readFileSync(join(dir, 'src/content/schemas.ts'), 'utf8')).toBe(snap.schemas);
    expect(readFileSync(join(dir, 'src/content/virtual-content.d.ts'), 'utf8')).toBe(snap.dts);
    expect(readFileSync(userEditsPath, 'utf8')).toBe(snap.userEdits);
    expect(readFileSync(layout.pageFull, 'utf8')).toBe(snap.page);
    expect(result).not.toContain(CONFORMED_MARKER);
  });

  it('scaffold failure → page + vite untouched, no content written', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;
    const pageBefore: string = readFileSync(layout.pageFull, 'utf8');
    const viteBefore: string = readFileSync(join(dir, 'vite.config.ts'), 'utf8');
    const scaffold = await import('../../tools/content-scaffold.js');
    vi.spyOn(scaffold, 'scaffoldContent').mockResolvedValue({
      ok: false as const,
      error: { code: 'invalid-name' as const, message: 'boom' },
    });

    const result: string = await runHandler(layout, 'create', 'File created successfully.');

    expect(readFileSync(layout.pageFull, 'utf8')).toBe(pageBefore);
    expect(readFileSync(join(dir, 'vite.config.ts'), 'utf8')).toBe(viteBefore);
    expect(existsSync(join(dir, 'src/content'))).toBe(false);
    expect(result).not.toContain(CONFORMED_MARKER);
  });

  it('workspace unavailable → fail-safe: returns the result without conforming', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;
    const handler = createContentRulesPostEditHandler({ workspaceFactory: () => null });

    const result: string = await handler.run(makeContext(layout, 'create'), 'File created successfully.');

    expect(result).not.toContain(CONFORMED_MARKER);
    expect(existsSync(join(dir, 'src/content'))).toBe(false);
  });
});

describe('contentRulesPostEditHandler — auto-conform (no dynamic RegExp)', () => {
  it('the conform implementation contains no `new RegExp(` with an interpolated value', () => {
    const src: string = readFileSync(join(__dirname, '..', 'content-conform.ts'), 'utf8');
    // Any `new RegExp(` is disallowed (the AST validation replaced all of them);
    // an interpolated one would be the ReDoS hazard the review flagged.
    expect(src).not.toMatch(/new RegExp\(/);
  });

  it('the rewritten page exposes the content-rooted .map() chain the source-mapper keys off', async () => {
    const layout: AppLayout = setupApp('src/pages/index.tsx', PAGE);
    dir = layout.appPath;

    await runHandler(layout, 'create', 'File created successfully.');
    const page: string = readFileSync(layout.pageFull, 'utf8');

    const { parse } = await import('@babel/parser');
    const ast = parse(page, { sourceType: 'module', plugins: ['jsx', 'typescript'] });
    expect(ast.program.body.length).toBeGreaterThan(0);
    expect(page).toMatch(/import \{ home \} from 'virtual:content'/);
    expect(page).toMatch(/home\.testimonials\.map\(/);
  });
});
