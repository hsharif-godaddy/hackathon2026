import type { ActiveFontThemeSuggest } from '@/app/[market]/develop/components/utils/findLatestFontThemeSuggest'
import type { ChatMessage, StreamingMessage } from '@/stores/useStreamingConversationStore'

type PanelMessage = ChatMessage | StreamingMessage

export function isFontSuggestPanelVisible(
  messages: PanelMessage[],
  suggest: ActiveFontThemeSuggest
): boolean {
  const suggestIdx = messages.findIndex((m) => m.id === suggest.messageId)
  if (suggestIdx < 0) return false

  for (let i = suggestIdx + 1; i < messages.length; i++) {
    const m = messages[i]
    if (m.role !== 'user') continue
    // Only isActionRequest messages (generated by buttons) should keep the panel visible
    // User-typed messages should hide the panel
    if (!m.metadata?.isActionRequest) return false
  }
  return true
}
