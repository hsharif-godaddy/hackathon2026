package fixers

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/airo-ai-builder/dev-runner/internal/preflight"
)

const defaultGoCodeBaseURL = "https://caas-gocode-prod.caas-prod.prod.onkatana.net"

type evalProbeValues struct {
	useS2S     bool
	awsProfile string
	baseURL    string
	apiKey     string
}

// EvalProbeEnvFixer generates evals/gosym-probe/.env using values from agents/.env.
type EvalProbeEnvFixer struct{}

func (f *EvalProbeEnvFixer) Fix(_ context.Context, projectRoot string) error {
	values := readAgentsEnvValues(projectRoot)
	envPath := filepath.Join(projectRoot, "evals/gosym-probe/.env")

	_, statErr := os.Stat(envPath)
	if statErr != nil && !os.IsNotExist(statErr) {
		return statErr
	}

	if os.IsNotExist(statErr) {
		content := fmt.Sprintf(`# GoSym Probe - Environment Configuration
# Generated by dev-runner preflight

GD_ENV=local.dev
OPENAI_BASE_URL="%s"
`, values.baseURL)
		if !values.useS2S {
			content += fmt.Sprintf(`PROBE_OPENAI_API_KEY="%s"
`, values.apiKey)
		}
		content += fmt.Sprintf(`
AWS_PROFILE=%s
OPENAI_MODEL=claude-sonnet-4-6
`, values.awsProfile)
		return writeFileAtomic(envPath, content)
	}

	if err := upsertEnvVarUnquoted(envPath, "GD_ENV", "local.dev"); err != nil {
		return err
	}
	if err := upsertEnvVar(envPath, "OPENAI_BASE_URL", values.baseURL); err != nil {
		return err
	}
	if values.useS2S {
		if err := removeEnvVar(envPath, "PROBE_OPENAI_API_KEY"); err != nil {
			return err
		}
	} else {
		if err := upsertEnvVar(envPath, "PROBE_OPENAI_API_KEY", values.apiKey); err != nil {
			return err
		}
	}
	// One-time cleanup: remove legacy key so existing .env files don't end up
	// with both OPENAI_API_KEY and PROBE_OPENAI_API_KEY side-by-side.
	if err := removeEnvVar(envPath, "OPENAI_API_KEY"); err != nil {
		return err
	}
	if err := upsertEnvVarUnquoted(envPath, "AWS_PROFILE", values.awsProfile); err != nil {
		return err
	}
	return upsertEnvVarUnquoted(envPath, "OPENAI_MODEL", "claude-sonnet-4-6")
}

// readAgentsEnvValues reads agents/.env and returns values required by gosym-probe.
func readAgentsEnvValues(projectRoot string) evalProbeValues {
	values := evalProbeValues{
		useS2S:     true,
		awsProfile: defaultAWSProfile,
		baseURL:    defaultGoCodeBaseURL,
	}

	env, err := preflight.ParseEnvFile(filepath.Join(projectRoot, "agents/.env"))
	if err != nil {
		return values
	}

	if strings.EqualFold(strings.TrimSpace(env["GOCODE_USE_S2S_AUTH"]), "false") {
		values.useS2S = false
	}
	if awsProfile := strings.TrimSpace(env["AWS_PROFILE"]); awsProfile != "" {
		values.awsProfile = awsProfile
	}
	if openAIBaseURL := strings.TrimSpace(env["OPENAI_BASE_URL"]); openAIBaseURL != "" {
		values.baseURL = openAIBaseURL
	}
	if openAIAPIKey := strings.TrimSpace(env["OPENAI_API_KEY"]); openAIAPIKey != "" {
		values.apiKey = openAIAPIKey
	}
	return values
}
