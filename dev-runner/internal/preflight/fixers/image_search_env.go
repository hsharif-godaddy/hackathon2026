package fixers

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/airo-ai-builder/dev-runner/internal/preflight"
)

const (
	imageSearchAWSProfile = "airobuild-dev-private-sso"
	imageSearchAWSRegion  = "us-west-2"
	imageSearchCertSecret = "/Katana/Secrets/airobuilde/proxy/dev-private-ecs/GETTY_CERT"
	imageSearchKeySecret  = "/Katana/Secrets/airobuilde/proxy/dev-private-ecs/GETTY_KEY"
)

// ImageSearchEnvFixer generates image-search-service/.env and fetches Getty
// client certificates from AWS Secrets Manager. It copies the GoCode API keys
// from agents/.env so the service shares the same credentials.
type ImageSearchEnvFixer struct{}

func (f *ImageSearchEnvFixer) Fix(ctx context.Context, projectRoot string) error {
	envPath := filepath.Join(projectRoot, "image-search-service/.env")
	certsDir := filepath.Join(projectRoot, "image-search-service", "certs")
	certFile := filepath.Join(certsDir, "client.crt")
	keyFile := filepath.Join(certsDir, "client.key")

	if err := os.MkdirAll(certsDir, 0o755); err != nil {
		return fmt.Errorf("creating certs dir: %w", err)
	}

	cert, err := fetchAWSSecret(ctx, projectRoot, imageSearchCertSecret, imageSearchAWSProfile, imageSearchAWSRegion)
	if err != nil {
		return fmt.Errorf("fetching Getty cert: %w", err)
	}
	key, err := fetchAWSSecret(ctx, projectRoot, imageSearchKeySecret, imageSearchAWSProfile, imageSearchAWSRegion)
	if err != nil {
		return fmt.Errorf("fetching Getty key: %w", err)
	}
	if err := os.WriteFile(certFile, []byte(strings.TrimSpace(cert)+"\n"), 0o600); err != nil {
		return fmt.Errorf("writing client cert: %w", err)
	}
	if err := os.WriteFile(keyFile, []byte(strings.TrimSpace(key)+"\n"), 0o600); err != nil {
		return fmt.Errorf("writing client key: %w", err)
	}

	// Inherit API keys from agents/.env if available.
	anthropicKey, openaiKey, openaiBaseURL := imageSearchAPIKeys(projectRoot)

	_, statErr := os.Stat(envPath)
	if statErr != nil && !os.IsNotExist(statErr) {
		return statErr
	}
	if os.IsNotExist(statErr) {
		content := fmt.Sprintf(`# Image Search Service - Environment Configuration
# Generated by dev-runner preflight

AWS_PROFILE=%s
AWS_REGION=%s

PORT=8080
LOG_LEVEL=info

QDRANT_HOST=127.0.0.1
QDRANT_PORT=6334
QDRANT_COLLECTION=image_analyses
QDRANT_API_KEY=

GETTY_AUTH_TYPE=sso-jwt
GETTY_UPSTREAM=https://getty-images-proxy.api.godaddy.com
GETTY_X_APP_KEY=airo-app-builder
GETTY_CERT_PATH=%s
GETTY_KEY_PATH=%s
GETTY_SSO_HOST=sso.godaddy.com
GETTY_RATE_LIMIT_RPS=50
GETTY_CONCURRENCY=10

ANTHROPIC_API_URL=https://caas-gocode-prod.caas-prod.prod.onkatana.net
ANTHROPIC_API_KEY=%s
HAIKU_RATE_LIMIT_RPS=20
HAIKU_CONCURRENCY=5

OPENAI_API_KEY=%s
OPENAI_BASE_URL=%s

S3_BUCKET=airo-image-analyses-dev
S3_REGION=us-west-2
S3_PREFIX=analyses/v1

DEFAULT_MIN_CACHED=5
DEFAULT_MAX_WAIT_SECONDS=30

SSO_HOST=sso.godaddy.com
AUTH_TYPE=none
JWKS_URL=https://airo-builder.test-godaddy.com/.well-known/jwks.json

ELASTIC_APM_SERVER_URL=
ELASTIC_APM_SERVICE_NAME=image-search-service
ELASTIC_APM_ENVIRONMENT=dev
`, imageSearchAWSProfile, imageSearchAWSRegion, certFile, keyFile, anthropicKey, openaiKey, openaiBaseURL)
		return writeFileAtomic(envPath, content)
	}

	// File exists — upsert required vars, cert paths, and sync API keys, preserve everything else.
	if err := upsertEnvVarUnquoted(envPath, "AWS_PROFILE", imageSearchAWSProfile); err != nil {
		return err
	}
	if err := upsertEnvVarUnquoted(envPath, "GETTY_AUTH_TYPE", "sso-jwt"); err != nil {
		return err
	}
	if err := upsertEnvVarUnquoted(envPath, "ANTHROPIC_API_URL", "https://caas-gocode-prod.caas-prod.prod.onkatana.net"); err != nil {
		return err
	}
	if err := upsertEnvVarUnquoted(envPath, "GETTY_CERT_PATH", certFile); err != nil {
		return err
	}
	if err := upsertEnvVarUnquoted(envPath, "GETTY_KEY_PATH", keyFile); err != nil {
		return err
	}
	if anthropicKey != "" {
		if err := upsertEnvVar(envPath, "ANTHROPIC_API_KEY", anthropicKey); err != nil {
			return err
		}
	}
	if openaiKey != "" {
		if err := upsertEnvVar(envPath, "OPENAI_API_KEY", openaiKey); err != nil {
			return err
		}
	}
	if openaiBaseURL != "" {
		if err := upsertEnvVar(envPath, "OPENAI_BASE_URL", openaiBaseURL); err != nil {
			return err
		}
	}
	return nil
}

// imageSearchAPIKeys reads GoCode API credentials from agents/.env.
func imageSearchAPIKeys(projectRoot string) (anthropicKey, openaiKey, openaiBaseURL string) {
	env, err := preflight.ParseEnvFile(filepath.Join(projectRoot, "agents/.env"))
	if err != nil {
		return "", "", ""
	}
	return env["ANTHROPIC_API_KEY"], env["OPENAI_API_KEY"], env["OPENAI_BASE_URL"]
}
