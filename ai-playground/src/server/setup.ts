#!/usr/bin/env node

import fs from 'fs'
import path from 'path'
import readline from 'readline'

interface SetupOptions {
  apiKey: string
  baseUrl?: string
}

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
})

async function question(query: string): Promise<string> {
  return new Promise(resolve => {
    rl.question(query, resolve)
  })
}

async function setup(): Promise<void> {
  console.log('🚀 AI Playground Setup\n')
  
  // Check if .env.local already exists
  const envPath = path.join(process.cwd(), '.env.local')
  if (fs.existsSync(envPath)) {
    const overwrite = await question('.env.local already exists. Overwrite? (y/N): ')
    if (overwrite.toLowerCase() !== 'y') {
      console.log('Setup cancelled.')
      process.exit(0)
    }
  }
  
  console.log('Please provide your OpenAI API key to get started.')
  console.log('You can get one from: https://platform.openai.com/api-keys\n')
  
  const apiKey = await question('Enter your OpenAI API key: ')
  
  if (!apiKey.trim()) {
    console.log('❌ API key is required to run the playground.')
    process.exit(1)
  }
  
  // Optional: OpenAI Base URL
  const baseUrl = await question('Enter OpenAI Base URL (leave empty for default): ')
  
  const options: SetupOptions = {
    apiKey: apiKey.trim(),
    ...(baseUrl.trim() && { baseUrl: baseUrl.trim() })
  }
  
  // Create .env.local file
  const envContent = `# AI Playground Environment Variables
# Generated by setup script

# OpenAI API Configuration
OPENAI_API_KEY=${options.apiKey}
${options.baseUrl ? `OPENAI_BASE_URL=${options.baseUrl}` : '# OPENAI_BASE_URL='}

# Default AI Configuration
DEFAULT_PROVIDER=openai
DEFAULT_MODEL=gpt-4o-mini
DEFAULT_TEMPERATURE=0.7
DEFAULT_MAX_TOKENS=2000

# AWS Bedrock Configuration (optional)
# AWS_REGION=us-west-2
# AWS_ACCESS_KEY_ID=
# AWS_SECRET_ACCESS_KEY=
# AWS_PROFILE=

# Anthropic Configuration (optional)
# ANTHROPIC_API_KEY=

# Debug Mode
DEBUG=false
`

  try {
    fs.writeFileSync(envPath, envContent)
    
    console.log('\n✅ Configuration saved to .env.local')
    console.log('\n🎯 Next steps:')
    console.log('   1. npm run dev    - Start the development server')
    console.log('   2. Open http://localhost:3000 in your browser')
    console.log('   3. Start chatting with the AI!\n')
    console.log('💡 Features to try:')
    console.log('   • Normal chat mode for quick questions')
    console.log('   • Agentic mode for complex problem solving')
    console.log('   • Try the example prompts in the interface')
  } catch (error) {
    console.error('❌ Failed to write configuration file:', error)
    process.exit(1)
  }
  
  rl.close()
}

setup().catch((error: Error) => {
  console.error('Setup failed:', error.message)
  process.exit(1)
})
