#!/usr/bin/env node

import fs from 'fs'
import path from 'path'
import readline from 'readline'

interface SetupOptions {
  apiKey: string
  baseUrl?: string
  awsRegion?: string
  awsProfile?: string
  setupType: string
}

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
})

async function question(query: string): Promise<string> {
  return new Promise(resolve => {
    rl.question(query, resolve)
  })
}

async function setup(): Promise<void> {
  console.log('🚀 AI Playground Setup\n')
  
  // Check if .env.local already exists
  const envPath = path.join(process.cwd(), '.env.local')
  if (fs.existsSync(envPath)) {
    const overwrite = await question('.env.local already exists. Overwrite? (y/N): ')
    if (overwrite.toLowerCase() !== 'y') {
      console.log('Setup cancelled.')
      process.exit(0)
    }
  }
  
  console.log('🔧 Configuration Options:')
  console.log('1. GoCode Proxy (recommended - full Claude access with streaming support)')
  console.log('2. AWS Bedrock (production environment alternative)\n')
  
  const setupType = await question('Choose setup type (1/2) [default: 1]: ') || '1'
  
  let apiKey = ''
  let baseUrl = ''
  let awsRegion = ''
  let awsProfile = ''
  
  if (setupType === '1') {
    // GoCode Proxy Configuration (now default)
    console.log('\n🌐 Setting up GoCode Proxy...')
    console.log('This provides full Claude access with streaming support through GoCode.')
    console.log('Get your API key from: https://caas.godaddy.com/home\n')
    
    apiKey = await question('Enter your GoCode API key: ')
    
    if (!apiKey.trim()) {
      console.log('❌ GoCode API key is required for proxy setup.')
      process.exit(1)
    }
    
    // Set GoCode URLs for both OpenAI and Anthropic
    baseUrl = 'https://caas-gocode-prod.caas-prod.prod.onkatana.net/v1'
    
    console.log('✅ Configuring GoCode proxy endpoints:')
    console.log(`   OpenAI: ${baseUrl}`)
    console.log(`   Anthropic: ${baseUrl}`)
    console.log('✅ This enables Claude streaming without issues!')
    
  } else if (setupType === '2') {
    // AWS Bedrock Configuration
    console.log('\n🚀 Setting up AWS Bedrock...')
    console.log('Bedrock provides access to Claude 4 and other advanced models.')
    console.log('This matches your production environment setup.')
    console.log('Setup AWS CLI first: https://docs.aws.amazon.com/cli/latest/userguide/getting-started-install.html\n')
    
    awsRegion = await question('Enter AWS region (e.g., us-west-2): ')
    awsProfile = await question('Enter AWS profile name (leave empty for default): ')
    
    if (!awsRegion.trim()) {
      awsRegion = 'us-west-2'
      console.log('Using default region: us-west-2')
    }
  } else {
    console.log('❌ Invalid option. Please choose 1 or 2.')
    process.exit(1)
  }
  
  const options: SetupOptions = {
    apiKey: apiKey.trim(),
    setupType,
    ...(baseUrl.trim() && { baseUrl: baseUrl.trim() }),
    ...(awsRegion.trim() && { awsRegion: awsRegion.trim() }),
    ...(awsProfile.trim() && { awsProfile: awsProfile.trim() })
  }
  
  // Create .env.local file
  const getDefaultProvider = () => {
    if (setupType === '1') return 'anthropic' // GoCode proxy with Anthropic
    return 'bedrock' // AWS Bedrock
  }
  
  const getDefaultModel = () => {
    return 'claude4' // Always use Claude 4
  }
  
  const getSetupDescription = () => {
    if (setupType === '1') return 'GoCode Proxy (Anthropic)'
    return 'AWS Bedrock (Production)'
  }
  
  const envContent = `# AI Playground Environment Variables
# Generated by setup script - Setup type: ${getSetupDescription()}

# GoCode Proxy Configuration (OpenAI + Anthropic)
${options.apiKey ? `OPENAI_API_KEY=${options.apiKey}` : '# OPENAI_API_KEY='}
${options.baseUrl ? `OPENAI_BASE_URL=${options.baseUrl}` : '# OPENAI_BASE_URL='}
${options.apiKey ? `ANTHROPIC_API_KEY=${options.apiKey}` : '# ANTHROPIC_API_KEY='}
${options.baseUrl ? `ANTHROPIC_BASE_URL=${options.baseUrl}` : '# ANTHROPIC_BASE_URL='}

# AWS Bedrock Configuration
${options.awsRegion ? `AWS_REGION=${options.awsRegion}` : '# AWS_REGION=us-west-2'}
${options.awsProfile ? `AWS_PROFILE=${options.awsProfile}` : '# AWS_PROFILE='}
# AWS_ACCESS_KEY_ID=
# AWS_SECRET_ACCESS_KEY=

# Default AI Configuration
DEFAULT_PROVIDER=${getDefaultProvider()}
DEFAULT_MODEL=${getDefaultModel()}
DEFAULT_TEMPERATURE=0.7
DEFAULT_MAX_TOKENS=2000

# Debug Mode
DEBUG=false
`

  try {
    fs.writeFileSync(envPath, envContent)
    
    console.log('\n✅ Configuration saved to .env.local')
    console.log('\n🎯 Next steps:')
    console.log('   1. npm run dev    - Start the development server')
    console.log('   2. Open http://localhost:3000 in your browser')
    console.log('   3. Start chatting with the AI!\n')
    
    if (setupType === '1') {
      console.log('🔧 GoCode Proxy Setup:')
      console.log('   • You\'re using GoCode proxy with Anthropic support')
      console.log('   • Get your API key from: https://caas.godaddy.com/home')
      console.log('   • Claude models will stream properly through Anthropic endpoint')
      console.log('   • Both OpenAI and Anthropic endpoints configured')
    } else {
      console.log('🔧 AWS Bedrock Setup:')
      console.log('   • You\'re using the production-grade setup')
      console.log('   • Ensure AWS CLI is configured with proper credentials')
      console.log('   • Models will use Claude 4 directly from Bedrock')
    }
    
    console.log('\n💡 Features to try:')
    console.log('   • Normal chat mode for quick questions')
    console.log('   • Agentic mode for complex problem solving')
    console.log('   • Try the example prompts in the interface')
  } catch (error) {
    console.error('❌ Failed to write configuration file:', error)
    process.exit(1)
  }
  
  rl.close()
}

setup().catch((error: Error) => {
  console.error('Setup failed:', error.message)
  process.exit(1)
})
