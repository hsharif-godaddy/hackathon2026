#!/bin/bash

# Airo AI Builder - Environment Setup Script
# Configures .env files for both app and agents with profile support

set -e  # Exit on any error

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration profiles
PROFILES=(
  "development:Local development with Docker deployment mode and GoCode models"
  "development-local:Local development with Local deployment mode and GoCode models"
  "testing:Integration testing setup with Docker mode and GoCode models"
  "aws-dev:Development with AWS Bedrock models and Docker mode"
)

print_header() {
    echo -e "${BLUE}=====================================${NC}"
    echo -e "${BLUE}  Airo AI Builder Environment Setup  ${NC}"
    echo -e "${BLUE}=====================================${NC}"
    echo
}

print_profiles() {
    echo -e "${YELLOW}Available profiles:${NC}"
    echo
    for profile in "${PROFILES[@]}"; do
        IFS=':' read -r name desc <<< "$profile"
        echo -e "  ${GREEN}$name${NC} - $desc"
    done
    echo
}

get_profile() {
    local profile=""
    
    if [ $# -eq 1 ]; then
        profile="$1"
    else
        print_profiles
        while true; do
            read -p "Select profile (development/development-local/testing/aws-dev): " profile
            case $profile in
                development|development-local|testing|aws-dev)
                    break
                    ;;
                *)
                    echo -e "${RED}Invalid profile. Please choose from: development, development-local, testing, aws-dev${NC}"
                    ;;
            esac
        done
    fi
    
    echo "$profile"
}

get_api_key() {
    local service="$1"
    local key=""
    
    echo -e "${YELLOW}Enter $service API key (or press Enter to skip):${NC}"
    read -s key
    echo "$key"
}

create_agents_env() {
    local profile="$1"
    local agents_env="agents/.env"
    
    echo -e "${BLUE}Configuring agents environment ($agents_env)...${NC}"
    
    # Get API key for LLM service
    local openai_key=""
    local openai_base_url=""
    local openai_model=""
    local aws_region=""
    
    case $profile in
        development|development-local|testing)
            echo -e "${YELLOW}Using GoCode configuration for LLM service${NC}"
            openai_base_url="https://caas-gocode-prod.caas-prod.prod.onkatana.net"
            openai_model="claude-sonnet-4"
            openai_key=$(get_api_key "GoCode/OpenAI")
            ;;
        aws-dev)
            echo -e "${YELLOW}Using AWS Bedrock configuration for LLM service${NC}"
            openai_model="claude-sonnet-4-20250514"
            aws_region="us-west-2"
            echo -e "${YELLOW}Make sure AWS credentials are configured (aws configure or IAM role)${NC}"
            ;;
    esac
    
    # Get additional service keys
    local getty_jwt=$(get_api_key "Getty Images SSO JWT")
    local unsplash_key=$(get_api_key "Unsplash")
    
    # Write agents .env file
    cat > "$agents_env" << EOF
# Airo AI Builder - Agents Configuration
# Generated by setup-env.sh with profile: $profile
# $(date)

NODE_ENV=development

# =============================================================================
# LLM Service Configuration
# =============================================================================

# OpenAI/GoCode API Configuration
OPENAI_API_KEY=$openai_key
EOF

    if [ -n "$openai_base_url" ]; then
        echo "OPENAI_BASE_URL=\"$openai_base_url\"" >> "$agents_env"
    fi
    
    echo "OPENAI_MODEL=\"$openai_model\"" >> "$agents_env"
    
    if [ -n "$aws_region" ]; then
        echo "" >> "$agents_env"
        echo "# AWS Configuration (for Bedrock)" >> "$agents_env"
        echo "AWS_REGION=$aws_region" >> "$agents_env"
    fi

    cat >> "$agents_env" << EOF

# =============================================================================
# Application Configuration
# =============================================================================

# Template version (v8 is current)
APP_TEMPLATE_DIR='app-templates/v8'

# Show token usage costs in UI
SHOW_USAGE_COST=true

# =============================================================================
# Image Services Configuration
# =============================================================================

# Image search driver (unsplash or getty)
IMAGE_SEARCH_DRIVER="unsplash"

# Unsplash API key (for image search)
UNSPLASH_ACCESS_KEY="$unsplash_key"

# Getty Images configuration
SSO_JWT=$getty_jwt
GETTY_API_URL=https://getty-images-proxy.api.test-godaddy.com/v1/search
GETTY_APP_KEY=airo-app-builder

# =============================================================================
# Development Configuration
# =============================================================================

# MySQL configuration (optional for advanced features)
MYSQL_ROOT_HOST=localhost
MYSQL_ROOT_PORT=3306
MYSQL_ROOT_USER=root
MYSQL_ROOT_PASS=

# Base directory for generated apps
APPS_BASE_DIR=/tmp/apps

# Server port
PORT=4000
EOF

    echo -e "${GREEN}✓ Created $agents_env${NC}"
}

create_app_env() {
    local profile="$1"
    local app_env="app/.env"
    
    echo -e "${BLUE}Configuring app environment ($app_env)...${NC}"
    
    # Get OpenAI key for app-level AI features
    local openai_key=$(get_api_key "OpenAI (for app name generation)")
    
    # Determine deployment mode based on profile
    local doc_apps="true"  # Default to Docker mode
    case $profile in
        development-local)
            doc_apps="false"
            ;;
    esac
    
    # Write app .env file
    cat > "$app_env" << EOF
# Airo AI Builder - App Configuration
# Generated by setup-env.sh with profile: $profile
# $(date)

# =============================================================================
# Development Configuration
# =============================================================================

NODE_ENV=development

# =============================================================================
# Authentication Configuration (GoDaddy SSO)
# =============================================================================

# SSO URLs
NEXT_PUBLIC_SSO_LOGIN_URL=https://sso.test-godaddy.com/login
NEXT_PUBLIC_SSO_LOGOUT_URL=https://sso.test-godaddy.com/logout

# Redirect URLs
NEXT_PUBLIC_LOGIN_REDIRECT_URL=https://airo-builder.test-godaddy.com/
NEXT_PUBLIC_LOGOUT_REDIRECT_URL=https://airo-builder.test-godaddy.com/

# Authentication settings
NEXT_PUBLIC_AUTH_IN_DEV=false
NEXT_PUBLIC_USE_MOCK_LOGIN=true

# Backend API URL
NEXT_PUBLIC_BACKEND_API_URL=http://localhost:3000

# =============================================================================
# TLS and Security Configuration
# =============================================================================

# TLS verification (disable for local Nomad development)
DISABLE_TLS_VERIFICATION=true

# Use API proxy for agent calls (temporary for SSL issues in testing)
USE_AGENT_PROXY=true

# =============================================================================
# AI/LLM Configuration
# =============================================================================

# OpenAI API Key for AI-powered features (app name generation, etc.)
OPENAI_API_KEY=$openai_key

# Optional: OpenAI configuration
# OPENAI_BASE_URL=https://api.openai.com
# OPENAI_MODEL="claude-sonnet-4"

# =============================================================================
# Container Orchestration (Nomad Configuration)
# =============================================================================

# Nomad API URL
NOMAD_API_URL=https://localhost:4646

# Nomad API timeout
NOMAD_API_TIMEOUT=30000

# =============================================================================
# Database Configuration
# =============================================================================

# Database provider (sqlite for development)
DATABASE_PROVIDER="sqlite"
DATABASE_URL="file:../data/airo-builder-platform.db"

# Production MySQL configuration (not used in development)
MYSQL_DB_PATH=placeholder-rds-host.region.rds.amazonaws.com
MYSQL_DB_PORT=3306
MYSQL_DB_NAME=airo_builder
MYSQL_DB_USERNAME=your-db-username
MYSQL_DB_PASSWORD=your-db-password

# =============================================================================
# AWS Configuration
# =============================================================================

# AWS Region
AWS_REGION=eu-central-1

# AWS Account ID (dev account)
AWS_ACCOUNT_ID=418549769352

# =============================================================================
# UI Configuration
# =============================================================================

# Show code editor button
NEXT_PUBLIC_SHOW_CODE_EDITOR=false

# Token usage display
SHOW_USAGE_COST=true

# =============================================================================
# Deployment Mode
# =============================================================================

# Docker deployment mode for app provisioning
# true = Docker containers (default for development)
# false = Local Node.js processes (for debugging)
DOC_APPS=$doc_apps
EOF

    echo -e "${GREEN}✓ Created $app_env${NC}"
}

backup_existing_files() {
    local timestamp=$(date +%Y%m%d_%H%M%S)
    
    if [ -f "agents/.env" ]; then
        cp "agents/.env" "agents/.env.backup_$timestamp"
        echo -e "${YELLOW}Backed up existing agents/.env to agents/.env.backup_$timestamp${NC}"
    fi
    
    if [ -f "app/.env" ]; then
        cp "app/.env" "app/.env.backup_$timestamp"
        echo -e "${YELLOW}Backed up existing app/.env to app/.env.backup_$timestamp${NC}"
    fi
}

validate_setup() {
    echo -e "${BLUE}Validating setup...${NC}"
    
    local errors=0
    
    # Check if directories exist
    if [ ! -d "agents" ]; then
        echo -e "${RED}❌ agents/ directory not found${NC}"
        errors=$((errors + 1))
    fi
    
    if [ ! -d "app" ]; then
        echo -e "${RED}❌ app/ directory not found${NC}"
        errors=$((errors + 1))
    fi
    
    # Check if template directory exists
    if [ ! -d "app-templates/v8" ]; then
        echo -e "${RED}❌ app-templates/v8/ directory not found${NC}"
        errors=$((errors + 1))
    fi
    
    if [ $errors -eq 0 ]; then
        echo -e "${GREEN}✓ Setup validation passed${NC}"
        return 0
    else
        echo -e "${RED}Setup validation failed with $errors errors${NC}"
        return 1
    fi
}

print_next_steps() {
    local profile="$1"
    
    echo
    echo -e "${GREEN}✅ Environment setup complete!${NC}"
    echo
    echo -e "${YELLOW}Next steps:${NC}"
    echo "1. Review and edit the generated .env files if needed:"
    echo "   - agents/.env"
    echo "   - app/.env"
    echo
    echo "2. Start the development servers:"
    echo "   ${BLUE}cd agents && pnpm install && pnpm run dev${NC}    # Port 4000"
    echo "   ${BLUE}cd app && pnpm install && pnpm run dev${NC}       # Port 3000"
    echo
    echo "3. Install app template dependencies:"
    echo "   ${BLUE}cd app-templates/v8 && pnpm install${NC}"
    echo
    
    case $profile in
        aws-dev)
            echo -e "${YELLOW}AWS-specific setup:${NC}"
            echo "4. Configure AWS credentials:"
            echo "   ${BLUE}aws configure${NC}"
            echo "   Or ensure your IAM role has access to Amazon Bedrock"
            echo
            ;;
        testing)
            echo -e "${YELLOW}Testing-specific setup:${NC}"
            echo "4. This profile is configured for integration testing"
            echo "   Make sure your test environment matches these settings"
            echo
            ;;
    esac
    
    echo -e "${BLUE}Profile used: $profile${NC}"
    echo -e "${BLUE}Deployment mode: $([ "$profile" = "development-local" ] && echo "Local processes" || echo "Docker containers")${NC}"
    echo -e "${BLUE}LLM provider: $([ "$profile" = "aws-dev" ] && echo "AWS Bedrock" || echo "GoCode")${NC}"
}

main() {
    print_header
    
    # Validate we're in the right directory
    if [ ! -f "CLAUDE.md" ]; then
        echo -e "${RED}Error: This script must be run from the airo-ai-builder root directory${NC}"
        exit 1
    fi
    
    # Get profile selection
    local profile=$(get_profile "$@")
    
    echo -e "${GREEN}Selected profile: $profile${NC}"
    echo
    
    # Validate setup prerequisites
    if ! validate_setup; then
        exit 1
    fi
    
    # Backup existing files
    backup_existing_files
    
    # Create environment files
    create_agents_env "$profile"
    create_app_env "$profile"
    
    # Print next steps
    print_next_steps "$profile"
}

# Run main function with all arguments
main "$@"