#!/bin/bash
set -e

# =============================================================================
# Qdrant Cluster Entrypoint
# =============================================================================
# Handles TLS certificate fetching and cluster bootstrap/join logic
#
# Environment Variables:
#   QDRANT_CLUSTER_FQDN       - Cluster discovery FQDN (required)
#   QDRANT_TLS_SECRET_ARN     - Name or ARN of Secrets Manager secret containing TLS cert (optional)
#   QDRANT_ENABLE_TLS         - Set to "true" to enable TLS (optional)
#   AWS_REGION                - AWS region for Secrets Manager (defaults to us-west-2)
# =============================================================================

QDRANT_CLUSTER_FQDN="${QDRANT_CLUSTER_FQDN:-qdrant.dev.airo.local}"
AWS_REGION="${AWS_REGION:-us-west-2}"

echo "============================================"
echo "Qdrant Cluster Entrypoint"
echo "Cluster FQDN: ${QDRANT_CLUSTER_FQDN}"
echo "TLS Enabled: ${QDRANT_ENABLE_TLS:-false}"
echo "============================================"

# -----------------------------------------------------------------------------
# TLS Certificate Setup
# -----------------------------------------------------------------------------
# Fetches TLS certificate from Secrets Manager and writes to /qdrant/tls/
# Secret format: {"crt": "...", "key": "...", "chain": "..."}
# Certificate is generated by qdrant-tls-bootstrap Lambda (self-signed CA)
# -----------------------------------------------------------------------------
setup_tls() {
    if [ "${QDRANT_ENABLE_TLS}" != "true" ]; then
        echo "TLS not enabled, skipping certificate setup"
        return 0
    fi

    if [ -z "${QDRANT_TLS_SECRET_ARN}" ]; then
        echo "ERROR: QDRANT_TLS_SECRET_ARN is required when TLS is enabled"
        exit 1
    fi

    echo "Fetching TLS certificate from Secrets Manager..."
    echo "Secret: ${QDRANT_TLS_SECRET_ARN}"
    echo "Region: ${AWS_REGION}"

    # ECS Fargate automatically provides credentials via the container metadata endpoint
    # AWS CLI will automatically use these credentials

    # Fetch secret using AWS CLI
    # Note: stderr is discarded to prevent leaking sensitive error details
    if ! SECRET_VALUE=$(aws secretsmanager get-secret-value \
        --secret-id "${QDRANT_TLS_SECRET_ARN}" \
        --region "${AWS_REGION}" \
        --query 'SecretString' \
        --output text 2>/dev/null); then
        echo "ERROR: Failed to fetch TLS secret from Secrets Manager"
        echo "Verify the secret exists and task role has secretsmanager:GetSecretValue permission"
        exit 1
    fi

    if [ -z "${SECRET_VALUE}" ] || [ "${SECRET_VALUE}" = "null" ]; then
        echo "ERROR: TLS secret is empty or null"
        exit 1
    fi

    # Parse JSON and write certificate files
    # Lambda stores: {"crt": "cert", "key": "private key", "chain": "CA cert"}
    echo "Writing TLS certificate files..."

    # Ensure TLS directory exists with restrictive permissions
    mkdir -p /qdrant/tls
    chmod 700 /qdrant/tls

    # Extract certificate components
    CERT=$(echo "$SECRET_VALUE" | jq -r '.crt // empty')
    CHAIN=$(echo "$SECRET_VALUE" | jq -r '.chain // empty')
    KEY=$(echo "$SECRET_VALUE" | jq -r '.key // empty')

    if [ -z "$CERT" ] || [ -z "$KEY" ]; then
        echo "ERROR: TLS secret missing required 'crt' or 'key' fields"
        echo "Expected JSON format: {\"crt\": \"...\", \"key\": \"...\", \"chain\": \"...\"}"
        exit 1
    fi

    # Write full certificate chain (cert + intermediate)
    if [ -n "$CHAIN" ]; then
        printf '%s\n%s\n' "$CERT" "$CHAIN" > /qdrant/tls/cert.pem
        echo "Wrote certificate with intermediate chain"
    else
        printf '%s\n' "$CERT" > /qdrant/tls/cert.pem
        echo "Wrote certificate (no intermediate chain)"
    fi

    printf '%s\n' "$KEY" > /qdrant/tls/key.pem

    # Set appropriate permissions (readable by owner only for key)
    chmod 644 /qdrant/tls/cert.pem
    chmod 600 /qdrant/tls/key.pem

    echo "TLS certificates written to /qdrant/tls/"
    echo "  - cert.pem: $(wc -l < /qdrant/tls/cert.pem) lines"
    echo "  - key.pem: $(wc -l < /qdrant/tls/key.pem) lines"

    # Set Qdrant TLS environment variables
    export QDRANT__SERVICE__ENABLE_TLS=true
    export QDRANT__TLS__CERT=/qdrant/tls/cert.pem
    export QDRANT__TLS__KEY=/qdrant/tls/key.pem

    echo "TLS configuration complete"
}

# -----------------------------------------------------------------------------
# Cluster Bootstrap/Join Logic
# -----------------------------------------------------------------------------
start_qdrant() {
    local protocol="http"
    if [ "${QDRANT_ENABLE_TLS}" = "true" ]; then
        protocol="https"
    fi

    echo "Performing DNS lookup for ${QDRANT_CLUSTER_FQDN}..."

    if DNS_RESULT=$(dig +short "$QDRANT_CLUSTER_FQDN" A 2>/dev/null) && [ -n "$DNS_RESULT" ]; then
        RECORD_COUNT=$(echo "$DNS_RESULT" | grep -cE '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' 2>/dev/null || echo 0)

        if [ "$RECORD_COUNT" -eq 0 ]; then
            echo "No valid IP records found."
            echo "Bootstrapping NEW Qdrant cluster..."
            exec ./qdrant --bootstrap "${protocol}://${QDRANT_CLUSTER_FQDN}:6335"
        else
            echo "Found ${RECORD_COUNT} DNS record(s)."
            echo "Joining EXISTING cluster..."
            exec ./qdrant --uri "${protocol}://${QDRANT_CLUSTER_FQDN}:6335"
        fi
    else
        echo "DNS lookup failed or returned empty result."
        echo "Bootstrapping NEW Qdrant cluster..."
        exec ./qdrant --bootstrap "${protocol}://${QDRANT_CLUSTER_FQDN}:6335"
    fi
}

# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------
if ! setup_tls; then
    echo "ERROR: TLS setup failed"
    exit 1
fi

start_qdrant
